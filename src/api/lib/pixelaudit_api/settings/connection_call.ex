defmodule PixelAudit.Api.Settings.ConnectionCall do
  @moduledoc """
  One call to an external system through a connection, as
  `PixelAudit.Api.Settings.Gateway` recorded it: a database query (`sql`,
  `params`, `result`) or an API call (`method`, `url`, the request's and
  the response's content type and body), when it started, how long it
  took, and the error if it failed.

  The id is a UUIDv7, generated by Postgres (`uuidv7()`), so the ids sort
  by time. Rows older than the retention are deleted by
  `PixelAudit.Api.Settings.CallsCleanupJob`.
  """

  use Ecto.Schema

  import Ecto.Changeset

  @type kind :: :query | :api_call

  @primary_key {:id, :binary_id, autogenerate: false, read_after_writes: true}
  @foreign_key_type :binary_id
  schema "settings_connection_calls" do
    belongs_to :connection, PixelAudit.Api.Settings.Connection
    field :kind, Ecto.Enum, values: [:query, :api_call]
    field :status, Ecto.Enum, values: [:ok, :error]
    field :started_at, :utc_datetime_usec
    field :duration_ms, :integer
    field :error, :string

    # A query.
    field :sql, :string
    field :params, PixelAudit.Api.JSON
    field :result, PixelAudit.Api.JSON

    # An API call.
    field :method, :string
    field :url, :string
    field :request_content_type, :string
    field :request_body, :string
    field :response_status, :integer
    field :response_content_type, :string
    field :response_body, :string
  end

  @fields [
    :connection_id,
    :kind,
    :status,
    :started_at,
    :duration_ms,
    :error,
    :sql,
    :params,
    :result,
    :method,
    :url,
    :request_content_type,
    :request_body,
    :response_status,
    :response_content_type,
    :response_body
  ]

  def changeset(call, attrs) do
    call
    |> cast(attrs, @fields)
    |> validate_required([:connection_id, :kind, :status, :started_at, :duration_ms])
    |> foreign_key_constraint(:connection_id)
  end
end
